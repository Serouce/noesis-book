interface DossierContextValue {
  activeDossier: DossierEntry | null;
  openDossier: (idOrEntry: string | DossierEntry) => void;
  closeDossier: () => void;
}

const DossierContext = createContext<DossierContextValue | null>(null);

export function DossierProvider({
  children,
  onDossierRead,
}: {
  children: ReactNode;
  onDossierRead?: (id: string) => void;
}) {
  const [activeDossier, setActiveDossier] = useState<DossierEntry | null>(null);

  const openDossier = useCallback(
    (idOrEntry: string | DossierEntry) => {
      const entry = typeof idOrEntry === 'string' ? DOSSIER_REGISTRY[idOrEntry] : idOrEntry;
      if (!entry) return;
      setActiveDossier(entry);
      onDossierRead?.(entry.id);
    },
    [onDossierRead],
  );

  const closeDossier = useCallback(() => {
    setActiveDossier(null);
  }, []);

  return (
    <DossierContext.Provider value={{ activeDossier, openDossier, closeDossier }}>
      {children}
    </DossierContext.Provider>
  );
}

export function useDossier() {
  const ctx = useContext(DossierContext);
  if (!ctx) {
    throw new Error('useDossier must be used within DossierProvider');
  }
  return ctx;
}
